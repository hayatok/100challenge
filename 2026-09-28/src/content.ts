function parse(lines: string): readonly Phrase[] {
  return Object.freeze(lines.trim().split('\n').map(line => {
    const [text, reading] = line.split('|');
    if (!text || !reading) throw new Error(`Malformed phrase: ${line}`);
    new TypingSession(reading);
    return Object.freeze({text, reading});
  }));
}


import type { Phrase } from './content.ts';
import type { DistrictArea, NormalEnemyKind, StageId } from './stages.ts';
import { TypingSession } from './typing.ts';

export type StagePhraseSet = {
  areas: Partial<Record<DistrictArea, Record<NormalEnemyKind, readonly Phrase[]>>>;
  rush: readonly Phrase[];
  boss: readonly Phrase[];
  counters: readonly Phrase[];
  lucky: readonly (readonly Phrase[])[];
};

function parse(source: string): readonly Phrase[] {
  return source.trim().split('\n').map((line) => {
    const divider = line.indexOf('|');
    if (divider < 1 || divider === line.length - 1) throw new Error(`Invalid stage phrase: ${line}`);
    const phrase = { text: line.slice(0, divider), reading: line.slice(divider + 1) };
    new TypingSession(phrase.reading);
    return phrase;
  });
}


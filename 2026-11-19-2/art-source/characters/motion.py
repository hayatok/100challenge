def leg_key(step,pelvis):
    z,lift,pitch,arm=step
    foot=math.radians(pitch)
    # Toe and heel roll around the extremity touching the floor.
    ankle=.125+lift+.113*(math.cos(foot)-1)+max(.182*math.sin(foot),-.100*math.sin(foot))
    down=.87+pelvis-ankle
    upper=.38; lower=.365
    reach=min(math.hypot(down,z),upper+lower-.00005)
    hip=-math.atan2(z,down)-math.acos((reach*reach+upper*upper-lower*lower)/(2*reach*upper))
    knee=math.pi-math.acos((upper*upper+lower*lower-reach*reach)/(2*upper*lower))
    return hip,knee,foot-hip-knee,math.radians(arm)


def source(clip,side,frame):
    i=(frame+side*6)%12
    if clip==2 and side==0:
        return LIMP[i]
    step=list((RUN if clip==1 else WALK)[i])
    if side:
        step[0]*=.975
        step[1]*=.94
        step[3]*=.92
    if clip==2:
        step[0]*=.79
        step[3]*=.71
    return step


def build():
    bpy.ops.object.armature_add()
    rig=bpy.context.object
    rig.name="Evacuation motion master"
    bpy.ops.object.mode_set(mode='EDIT')
    rig.data.edit_bones.remove(rig.data.edit_bones[0])
    names=("Left gait","Right gait","Weight transfer")
    for j,name in enumerate(names):
        b=rig.data.edit_bones.new(name)
        b.head=(j*.11,0,0);b.tail=(j*.11,0,.3)
    bpy.ops.object.mode_set(mode='POSE')
    lines=["// Generated by Blender from art-source/characters/motion.py.",
           "// Twelve keyed poses per cycle, followed by the duplicated contact pose."]
    samples=[]
    for clip in range(3):
        rows=[[],[],[]]
        sampled=[[],[],[]]
        for k in range(13):
            frame=1+clip*16+k
            body=TRUNK[clip][k%12]
            for side in range(3):
                values=(leg_key(source(clip,side,k),body[0]) if side<2 else
                        (body[0],body[1],math.radians(body[2]),math.radians(body[3])))
                bone=rig.pose.bones[names[side]]
                # Four scalar channels preserve unwrapped relative hinge angles.
                for i,v in enumerate(values):
                    bone["channel%d"%i]=v
                    bone.keyframe_insert(data_path='["channel%d"]'%i,frame=frame,group=bone.name)
        for k in range(13):
            bpy.context.scene.frame_set(1+clip*16+k)
            for side in range(3):
                b=rig.pose.bones[names[side]]
                values=tuple(b["channel%d"%i] for i in range(4))
                rows[side].append("float4("+",".join("%.6f"%v for v in values)+")")
                sampled[side].append(values)
        for side,name in enumerate(("Left","Right","Body")):
            lines.append("static const float4 %s%s[13] = {"%(("Walk","Run","Limp")[clip],name))
            lines.append(",\n".join(rows[side])+"};")
        samples.extend(sampled)
    write_contact_tables(samples)
    OUT.write_text("\n".join(lines)+"\n"+(HERE/"pose_runtime.hlsl").read_text(encoding="ascii"),encoding="ascii")


def write_contact_tables(samples):
    lines=[
        "// Generated from the same Blender gait samples as ActorMotion.cginc.",
        "using UnityEngine;",
        "",
        "namespace Evac",
        "{",
        "    internal static partial class ActorGait",
        "    {",
        "        static readonly Vector4[] Keys =",
        "        {",
    ]
    for row in samples:
        for key in row:
            lines.append("            new Vector4("+", ".join(f"{value:.6f}f" for value in key)+"),")
    lines.extend(("        };", "", "        static readonly float[] StanceEnd =", "        {"))
    for clip in range(3):
        for side in range(2):
            offset=side*6
            end=max(i for i in range(12) if source(clip,side,i-offset)[1]==0)
            lines.append(f"            {end:.1f}f,")
    lines.extend(("        };", "    }", "}", ""))
    (ASSETS/"Scripts/World/ActorGait.Keys.cs").write_text("\n".join(lines),encoding="ascii")


build()

export function cleanSeriesLabel(label = '') {
  let text = String(label)
    .replace(/#?[A-Z]\d{4,}_/g, '')
    .replace(/(^|\s*\/\s*)\d+_/g, '$1')
    .replace(/(^|\s*\/\s*)\d+[_ ](?=[^\d])/g, '$1')
    .replace(/\bTL_/g, '').replace(/\*製造業/g, '製造業')
    .replace(/\s*\/\s*観測値/g, '').replace(/\s*\/\s*統合集計/g, '')
    .replace(/年間エネルギー種別エネルギー消費量_エネルギー種別_([^_]+)_平均/g, '家庭の年間$1消費量')
    .replace(/生活保護被保護実人員（月平均人口千人当たり）/g, '生活保護を受ける人（月平均・人口千人当たり）')
    .replace(/収録版：令和(\d+)年度/g, (_, n) => `${2018 + Number(n)}年度の表`)
    .replace(/_/g, '・');
  if (text.includes('家庭の年間')) text = text.replace(/^全国\s*\/\s*/, '');
  return [...new Set(text.split(/\s*\/\s*/).map(part => part.trim()).filter(Boolean))].join(' ／ ');
}

